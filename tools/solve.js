// Proves every level in tools/levels-src.js is solvable, sets the tower
// budget and star thresholds, and writes js/levels.js for the game.
// Usage: node tools/solve.js           (check + write)
//        node tools/solve.js --check   (check only; exits 1 if js/levels.js is stale or a level fails)
//        node tools/solve.js --md      (also print a Markdown results table)
const fs = require('fs');
const path = require('path');
const L = require('../js/logic.js');
const SOURCE = require('./levels-src.js');

const OUT = path.join(__dirname, '..', 'js', 'levels.js');
const MAX_HINT_SOLUTIONS = 40;
const MAX_TOWERS = 8;
const MAX_SOLUTIONS = 2000;

// Mechanics a level uses, for the results table.
function mechanics(src) {
  const all = src.map.join('');
  const m = [];
  if (all.includes('Q')) m.push('quiet');
  if (all.includes('B')) m.push('busy');
  if (src.dishes) m.push('dish');
  if (all.includes('S')) m.push('relay');
  if (/[/L]/.test(all)) m.push('panel');
  return m.join('+') || 'basic';
}

// Dish levels name how many dishes they offer. The standard tower budget is
// then the smallest that still makes the level solvable, unless the source
// sets `towers` itself. Other levels get exactly the towers they need.
function solveLevel(grid, src) {
  if (!src.dishes) return { res: L.solve(grid, MAX_TOWERS, MAX_SOLUTIONS), masts: null };
  const caps = src.towers !== undefined ? [src.towers] : [...Array(MAX_TOWERS + 1).keys()];
  for (const masts of caps) {
    const res = L.solve(grid, MAX_TOWERS, MAX_SOLUTIONS, { towers: masts, dishes: src.dishes });
    if (res.min !== null) return { res, masts };
  }
  return { res: { min: null, solutions: [] }, masts: null };
}

let failed = false;
const rows = [];
const levels = SOURCE.map((src, i) => {
  const grid = L.parseLevel(src);
  const t0 = process.hrtime.bigint();
  const { res, masts } = solveLevel(grid, src);
  const ms = Number(process.hrtime.bigint() - t0) / 1e6;
  const label = `${String(i + 1).padStart(2)}. ${src.name.padEnd(18)}`;
  if (res.min === null) {
    console.log(`${label} UNSOLVABLE`);
    failed = true;
    return null;
  }
  // Every solution the solver returns must also pass the game's own check.
  if (!res.solutions.every((s) => L.isSolved(grid, s))) {
    console.log(`${label} SOLVER/RULES DISAGREE`);
    failed = true;
    return null;
  }
  // Star thresholds are in moves (each place, move or remove is one move;
  // turning a dish is free).
  // 3 stars: a perfect run, one move per tower in the smallest solution.
  // 2 stars: some slack for experimenting.
  const three = res.min;
  const two = res.min + Math.max(2, res.min);
  const nTargets = L.targets(grid).length;
  const budget = src.dishes ? `${masts}+${src.dishes}d` : `${res.min}`;
  console.log(`${label} ${`${grid.width}x${grid.height}`.padEnd(5)}  targets ${String(nTargets).padStart(2)}  ` +
    `towers ${res.min} (budget ${budget.padEnd(5)})  solutions ${String(res.solutions.length).padStart(4)}${res.capped ? '+' : ' '}  ` +
    `stars: 3 at <=${three}, 2 at <=${two}  ${ms.toFixed(1)} ms  [${mechanics(src)}]`);
  rows.push({ n: i + 1, name: src.name, mech: mechanics(src), min: res.min, budget, sols: res.solutions.length + (res.capped ? '+' : ''), ms, three, two });
  const out = {
    name: src.name,
    hint: src.hint,
    radius: src.radius,
    towers: src.dishes ? masts : res.min,
  };
  if (src.dishes) out.dishes = src.dishes;
  if (src.chapter) out.chapter = src.chapter;
  if (src.callout) out.callout = src.callout;
  out.stars = { three, two };
  out.map = src.map;
  out.solutions = res.solutions.slice(0, MAX_HINT_SOLUTIONS);
  return out;
});

if (failed) process.exit(1);

const body = '// Generated by tools/solve.js from tools/levels-src.js. Do not edit by hand.\n' +
  `const LEVELS = ${JSON.stringify(levels, null, 1)
    .replace(/\[\n\s+(\d+),\n\s+(\d+)\n\s+\]/g, '[$1,$2]')
    .replace(/\[\n\s+(\d+),\n\s+(\d+),\n\s+(\d+)\n\s+\]/g, '[$1,$2,$3]')};\n` +
  "if (typeof module !== 'undefined' && module.exports) module.exports = LEVELS;\n";

if (process.argv.includes('--md')) {
  console.log('\n| Level | Name | Mechanics | Min towers | Budget | Solutions | 3 stars | 2 stars | Solve time |');
  console.log('|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) console.log(`| ${r.n} | ${r.name} | ${r.mech} | ${r.min} | ${r.budget} | ${r.sols} | ${r.three} | ${r.two} | ${r.ms.toFixed(1)} ms |`);
  console.log(`\nTotal solve time: ${rows.reduce((a, r) => a + r.ms, 0).toFixed(0)} ms`);
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) { console.log('js/levels.js is out of date. Run: node tools/solve.js'); process.exit(1); }
  console.log(`All ${levels.length} levels solvable; js/levels.js is up to date.`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`All ${levels.length} levels solvable. Wrote js/levels.js`);
}
