#!/usr/bin/env node
// Builds js/story.js from Iris's design files, so story text and art are
// never retyped:
//   design/story-data.json     -> window.STORY (copied as-is: scenes, lines, level lines, town)
//   design/portrait-*.svg      -> window.STORY_ART.portraits[name][mood] (inner markup of each 96x96 mood)
//   design/town-hero.svg       -> window.STORY_ART.town (the scene markup, without its <style>; the
//                                 CSS lives in css/story.css, scoped to .town-svg)
// Ids inside the art are written as "{ID}-..." and made unique per copy at runtime.
// Usage: node tools/build-story.js         write js/story.js
//        node tools/build-story.js --check fail if js/story.js is out of date
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');

function build() {
  const story = JSON.parse(read('design/story-data.json'));
  const portraits = {};
  for (const name of Object.values(story.speakers).map((s) => s.portrait).filter(Boolean)) {
    const svg = read(`design/portrait-${name}.svg`);
    const re = /<svg[^>]*viewBox="0 0 96 96"[^>]*aria-label="[A-Za-z]+, (neutral|happy|worried)"[^>]*>([\s\S]*?)<\/svg>/g;
    const moods = {};
    let m;
    while ((m = re.exec(svg))) {
      let inner = m[2].trim();
      const ids = [...new Set([...inner.matchAll(/id="([^"]+)"/g)].map((x) => x[1]))];
      ids.forEach((id, n) => { inner = inner.split(`"${id}"`).join(`"{ID}-${n}"`).split(`#${id})`).join(`#{ID}-${n})`); });
      moods[m[1]] = inner.replace(/\n/g, '');
    }
    for (const mood of ['neutral', 'happy', 'worried']) if (!moods[mood]) throw new Error(`portrait-${name}.svg has no ${mood} mood`);
    portraits[name] = moods;
  }
  let town = read('design/town-hero.svg');
  town = town.replace(/^[\s\S]*?<style>[\s\S]*?<\/style>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const ids = [...new Set([...town.matchAll(/ id="([^"]+)"/g)].map((x) => x[1]))];
  for (const id of ids) town = town.split(`id="${id}"`).join(`id="{ID}-${id}"`).split(`#${id})`).join(`#{ID}-${id})`);
  town = town.replace(/\n\s*/g, '\n');
  const art = { portraits, town };
  return '// Generated by tools/build-story.js from design/story-data.json, design/portrait-*.svg\n' +
    '// and design/town-hero.svg. Do not edit: change the design files and rerun the tool.\n' +
    '(function (root) {\n' +
    `  const STORY = ${JSON.stringify(story, null, 1)};\n` +
    `  const STORY_ART = ${JSON.stringify(art)};\n` +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = { STORY, STORY_ART };\n" +
    '  else { root.STORY = STORY; root.STORY_ART = STORY_ART; }\n' +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
}

const out = build();
const file = path.join(ROOT, 'js/story.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== out) { console.error('js/story.js is out of date. Run: node tools/build-story.js'); process.exit(1); }
  console.log('js/story.js is up to date.');
} else {
  fs.writeFileSync(file, out);
  console.log(`Wrote js/story.js (${out.length} bytes).`);
}
